    private fun createCard(question: String, answer: String, hint: String): FlashcardEntity {
        return FlashcardEntity(
            deckId = 0L, // will be set on insert
            question = question,
            answer = answer,
            hint = hint,
            intervalDays = 0.0,
            repetitionCount = 0,
            easeFactor = 2.5,
            dueDate = 0L,
            status = CardStatus.NEW,
            isHeavy = false
        )
    }
